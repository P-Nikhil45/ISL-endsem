"""Generate an encrypted client/server voting demo with selectable algorithms."""
import argparse
import ast
import hashlib
import json
import re
import secrets
from pathlib import Path

TEMPLATES = Path(__file__).resolve().parent / "templates" / "authenticated_socket"
SIGNATURE_TEMPLATES = Path(__file__).resolve().parent / "templates" / "file" / "signature.py"

OPTIONS = {
    "symmetric": ("AES-128", "AES-192", "AES-256", "DES", "Triple-DES"),
    "hash": ("SHA256", "SHA512", "SHA1", "MD5", "CUSTOM32"),
    "signature": ("RSA", "ElGamal", "Schnorr"),
}
DEFAULTS = {"symmetric": "AES-256", "hash": "SHA512", "signature": "ElGamal"}


def normalize(value):
    return re.sub(r"[^a-z0-9]", "", value.lower())


def canonical_algorithm(category, value):
    cleaned = normalize(value)
    aliases = {"symmetric": {"aes": "AES-256", "3des": "Triple-DES", "des3": "Triple-DES"}}
    if cleaned in aliases.get(category, {}):
        return aliases[category][cleaned]
    for choice in OPTIONS[category]:
        if normalize(choice) == cleaned:
            return choice
    raise ValueError("Choose one of: " + ", ".join(OPTIONS[category]))


def without_common_import(source):
    source = source.replace("from common import *\n", "")
    return re.sub(r'\nif __name__ == "__main__":.*\Z', "\n", source, flags=re.S)


def selected_signature_constants(algorithm):
    source = SIGNATURE_TEMPLATES.read_text(encoding="utf-8")
    for block in source.split("# template: ")[1:]:
        label, code = block.split("\n", 1)
        if label.strip() == algorithm + "/constants":
            return code.strip()
    return ""


def create_key_material(selected, config):
    """Load the fixed educational keys and keep private values in role-specific outputs."""
    keys = json.loads((TEMPLATES / "hardcoded_keys.json").read_text(encoding="utf-8"))
    signature_keys = keys["signatures"][selected["signature"]]
    authority_keys = keys["signatures"]["RSA"]
    paillier_private = keys["paillier_private"]
    lam = int(paillier_private["lambda"])
    server_share = secrets.randbelow(lam - 1) + 1
    authority_share = lam - server_share
    public = {"title": config["title"],
              "server_rsa": keys["server_rsa_public"],
              "client_signature": signature_keys["public"],
              "paillier": keys["paillier_public"],
              "candidate_ids": config["candidates"],
              "symmetric": selected["symmetric"], "hash": selected["hash"],
              "signature": selected["signature"]}
    public["authority_rsa"] = authority_keys["public"]
    return {"public": public,
            "server_rsa_private": keys["server_rsa_private"],
            "paillier_server_share": {"lambda_share": str(server_share),
                                      "mu": paillier_private["mu"]},
            "paillier_authority_share": {"lambda_share": str(authority_share)},
            "authority_signing_private": authority_keys["private"],
            "client_signing_private": signature_keys["private"],
            "search_index_key": hashlib.sha256(
                ("constituency-index-v1:" + keys["server_rsa_private"]).encode("utf-8")).hexdigest()}


def generate_sources(selected, config, key_material=None):
    key_material = key_material or create_key_material(selected, config)
    common = (TEMPLATES / "common.py").read_text(encoding="utf-8")
    server = without_common_import((TEMPLATES / "server.py").read_text(encoding="utf-8"))
    client = without_common_import((TEMPLATES / "client.py").read_text(encoding="utf-8"))
    prefix = (
        "# Generated by generate_authenticated_socket_solution.py. Keep role files separate.\n"
        "CRYPTO = " + repr(selected) + "\n"
        "CONFIG = " + repr(config) + "\n"
        "SYMMETRIC_ALGORITHM = CRYPTO['symmetric']\n"
        "HASH_ALGORITHM = CRYPTO['hash']\n"
        "SIGNATURE_ALGORITHM = CRYPTO['signature']\n"
        "SEARCH_INDEX_KEY = " + repr(key_material["search_index_key"]) + "\n"
    )
    public_source = "PUBLIC = " + repr(key_material["public"]) + "\n"
    sig_constants = selected_signature_constants(selected["signature"])
    if sig_constants:
        common += "\n\n# Selected signature scheme parameters\n" + sig_constants + "\n"

    runner = '''\n\nif __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, EOFError, KeyboardInterrupt) as exc:
        print("Operation stopped:", exc)
'''
    server_keys = ("SERVER_RSA_PRIVATE_PEM = " + repr(key_material["server_rsa_private"]) + "\n"
                   "PAILLIER_SERVER_SHARE = " + repr(key_material["paillier_server_share"]) + "\n")
    client_keys = "CLIENT_SIGNING_KEY = " + repr(key_material["client_signing_private"]) + "\n"
    authority_keys = ("AUTHORITY_SHARE = " + repr(key_material["paillier_authority_share"]) + "\n"
                      "AUTHORITY_SIGNING_PRIVATE_PEM = " + repr(key_material["authority_signing_private"]) + "\n")
    server_source = prefix + public_source + server_keys + "\n" + common + "\n\n" + server + runner
    client_source = prefix + public_source + client_keys + "\n" + common + "\n\n" + client + runner
    authority_template = without_common_import((TEMPLATES / "authority.py").read_text(encoding="utf-8"))
    authority_source = prefix + public_source + authority_keys + "\n" + common + "\n\n" + authority_template + runner
    for filename, source in (("server.py", server_source), ("client.py", client_source)):
        ast.parse(source, filename=filename)
    ast.parse(authority_source, filename="authority.py")
    return server_source, client_source, authority_source


def create_solution(title, output_dir, *, symmetric="AES-256", hash_algorithm="SHA512",
                    signature="ElGamal", port=8765, candidates=None, search="SSE",
                    tsa_port=None, opens_at=None, closes_at=None):
    """Create a standalone encrypted voting demo in a new output folder."""
    if not title.strip():
        raise ValueError("Enter a project name.")
    if not 1024 <= port <= 65535:
        raise ValueError("Choose a port from 1024 to 65535.")
    selected = {
        "symmetric": canonical_algorithm("symmetric", symmetric),
        "hash": canonical_algorithm("hash", hash_algorithm),
        "signature": canonical_algorithm("signature", signature),
    }
    if candidates is None:
        candidate_ids = ["1", "2", "3"]
    elif isinstance(candidates, str):
        candidate_ids = [value.strip() for value in candidates.split(",") if value.strip()]
    else:
        candidate_ids = [str(value).strip() for value in candidates if str(value).strip()]
    if not candidate_ids or len(candidate_ids) > 20 or len(set(candidate_ids)) != len(candidate_ids):
        raise ValueError("Enter 1 to 20 unique candidate IDs.")
    if any(len(value) > 40 for value in candidate_ids):
        raise ValueError("Candidate IDs must be 40 characters or fewer.")
    config = {"title": title.strip(), "host": "127.0.0.1", "port": port,
              "candidates": candidate_ids}
    target = Path(output_dir).resolve()
    if target.exists():
        raise FileExistsError(f"Output folder already exists: {target}")
    server_source, client_source, authority_source = generate_sources(selected, config)
    target.mkdir(parents=True, exist_ok=False)
    (target / "server.py").write_text(server_source, encoding="utf-8")
    (target / "client.py").write_text(client_source, encoding="utf-8")
    (target / "authority.py").write_text(authority_source, encoding="utf-8")
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--title", default="Secure Voting Demo")
    parser.add_argument("--symmetric", "--encryption", dest="symmetric", choices=OPTIONS["symmetric"])
    parser.add_argument("--hash", "--hashing", dest="hash_algorithm", choices=OPTIONS["hash"])
    parser.add_argument("--signature", "--verification", dest="signature", choices=OPTIONS["signature"])
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--candidates", help="Comma-separated candidate IDs (default: 1,2,3)")
    args = parser.parse_args()

    if args.output is None:
        args.title = input("Project title [Secure Voting Demo]: ").strip() or args.title
        args.candidates = input("Candidate IDs, comma-separated [1,2,3]: ").strip() or args.candidates or "1,2,3"
        for category, arg_name in (("symmetric", "symmetric"), ("hash", "hash_algorithm"),
                                   ("signature", "signature")):
            label = "Signature / verification" if category == "signature" else category.title()
            print("\n" + label + " options: " + " / ".join(OPTIONS[category]))
            answer = input(f"{label} [{DEFAULTS[category]}]: ").strip() or DEFAULTS[category]
            setattr(args, arg_name, answer)
        args.output = Path(input("New output folder [generated/voting_demo]: ").strip() or "generated/voting_demo")

    try:
        target = create_solution(args.title, args.output, symmetric=args.symmetric or DEFAULTS["symmetric"],
                                 hash_algorithm=args.hash_algorithm or DEFAULTS["hash"],
                                 signature=args.signature or DEFAULTS["signature"], port=args.port,
                                 candidates=args.candidates)
    except (ValueError, OSError) as exc:
        parser.exit(1, f"Could not generate solution: {exc}\n")
    print(f"Created: {target}\nGenerated files: server.py, client.py and authority.py")
    print("Educational keys are split across server and authority roles. Distribute authority.py separately.")


if __name__ == "__main__":
    main()
